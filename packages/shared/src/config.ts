/** Two ticks, like a read receipt: the faded one is the paper's claim, the solid one is our re-run landing on it. */
function ticks(color: string, faded: number, width: number) {
  const line = `fill="none" stroke="${color}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round"`;
  return `<path d="${FIRST_TICK}" ${line} stroke-opacity="${faded}"/><path d="${SECOND_TICK}" ${line}/>`;
}

