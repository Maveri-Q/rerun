/**
 * Creates the testnet accounts the project needs (build step 1):
 *
 *   owner   rerun-<id>.testnet        deployer + contract owner      (faucet-funded)
 *   lab     rerun-lab-<id>.testnet    the Lab agent account (local mode)  (faucet-funded)
 *   rerun.<owner>                     the market contract           (funded by owner)
 *   tusdc.<owner>                     mock-ft collateral token      (funded by owner)
 *
 * Keys are generated locally and written to the repo-root .env.testnet (gitignored).
 * Testnet only; the faucet is https://helper.nearprotocol.com/account (the one near-cli-rs
 * uses for `sponsor-by-faucet-service`).
 *
 *   pnpm testnet:accounts            # refuses if .env.testnet already exists
 *   pnpm testnet:accounts --force
 */
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { config } from "dotenv";
import { Account, JsonRpcProvider, KeyPair, yoctoToNear, type KeyPairString } from "near-api-js";

const root = path.resolve(import.meta.dirname, "..");
config({ path: path.join(root, ".env"), quiet: true });

const RPC_URL = process.env.NEAR_TESTNET_RPC_URL || "https://test.rpc.fastnear.com";
const FAUCET_URL = process.env.NEAR_TESTNET_FAUCET_URL || "https://helper.nearprotocol.com/account";
const OUT = path.join(root, ".env.testnet");
const EXPLORER = "https://testnet.nearblocks.io/address/";

const provider = new JsonRpcProvider({ url: RPC_URL });

async function faucetCreate(accountId: string, key: KeyPair): Promise<void> {
  const res = await fetch(FAUCET_URL, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ newAccountId: accountId, newAccountPublicKey: key.getPublicKey().toString() }),
  });
  if (!res.ok) throw new Error(`faucet ${res.status} for ${accountId}: ${(await res.text()).slice(0, 300)}`);
  // The faucet answers before the account is visible on every RPC node; wait for it.
  for (let i = 0; i < 30; i++) {
    try {
      await new Account(accountId, provider).getState();
      return;
    } catch {
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
  throw new Error(`${accountId} not visible on ${RPC_URL} after 30s`);
}

async function main() {
  if (existsSync(OUT) && !process.argv.includes("--force")) {
    console.error(`${OUT} already exists. Re-run with --force to create a new set of accounts.`);
    process.exitCode = 1;
    return;
  }

  const id = randomBytes(3).toString("hex");
  const ownerId = `rerun-${id}.testnet`;
  const labId = `rerun-lab-${id}.testnet`;
  const contractId = `rerun.${ownerId}`;
  const ftId = `tusdc.${ownerId}`;
  const keys = {
    owner: KeyPair.fromRandom("ed25519"),
    lab: KeyPair.fromRandom("ed25519"),
    contract: KeyPair.fromRandom("ed25519"),
    ft: KeyPair.fromRandom("ed25519"),
  };

  console.log(`faucet: creating ${ownerId}`);
  await faucetCreate(ownerId, keys.owner);
  console.log(`faucet: creating ${labId}`);
  await faucetCreate(labId, keys.lab);

  const owner = new Account(ownerId, provider, keys.owner.toString() as KeyPairString);
  const balance = await owner.getBalance();
  // Keep about half for the owner (gas, market creation); split the rest.
  const toContract = (balance * 30n) / 100n;
  const toFt = (balance * 15n) / 100n;

  console.log(`creating ${contractId} with ${yoctoToNear(toContract)} NEAR`);
  await owner.createSubAccount({ accountOrPrefix: "rerun", publicKey: keys.contract.getPublicKey(), nearToTransfer: toContract });
  console.log(`creating ${ftId} with ${yoctoToNear(toFt)} NEAR`);
  await owner.createSubAccount({ accountOrPrefix: "tusdc", publicKey: keys.ft.getPublicKey(), nearToTransfer: toFt });

  const lines = [
    "# Generated by `pnpm testnet:accounts`. Testnet only. Never commit this file.",
    `TESTNET_OWNER_ACCOUNT=${ownerId}`,
    `TESTNET_OWNER_PRIVATE_KEY=${keys.owner.toString()}`,
    `TESTNET_LAB_ACCOUNT=${labId}`,
    `TESTNET_LAB_PRIVATE_KEY=${keys.lab.toString()}`,
    `TESTNET_CONTRACT_ACCOUNT=${contractId}`,
    `TESTNET_CONTRACT_PRIVATE_KEY=${keys.contract.toString()}`,
    `TESTNET_FT_ACCOUNT=${ftId}`,
    `TESTNET_FT_PRIVATE_KEY=${keys.ft.toString()}`,
    "",
  ];
  writeFileSync(OUT, lines.join("\n"), { mode: 0o600 });

  console.log(`\nwrote ${OUT}`);
  for (const a of [ownerId, labId, contractId, ftId]) {
    const state = await new Account(a, provider).getBalance();
    console.log(`  ${a.padEnd(34)} ${yoctoToNear(state, 3).padStart(8)} NEAR  ${EXPLORER}${a}`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
